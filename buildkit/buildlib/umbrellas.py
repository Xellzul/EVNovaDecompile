def check(tu_dir):
    """Every umbrella has a row and every row an umbrella; else stop, naming them."""
    have = {os.path.splitext(f)[0] for f in os.listdir(tu_dir) if f.endswith((".c", ".m"))}
    if have != set(OBJECT):
        raise SystemExit("umbrellas.OBJECT is out of step with %s: no row %s, no file %s" % (tu_dir, sorted(have - set(OBJECT)), sorted(set(OBJECT) - have)))
    return {v: k for k, v in OBJECT.items()}
